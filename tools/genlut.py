#!/usr/bin/env python3
"""
genlut.py - turn measured colour tables into the filter's lookup tables.

Input:  JSON files written by the measurement procedure in tools/measure_luts.sh
        (a list of [[R,G,B], [out...]] pairs, the first 33^3 entries being the
        grid in R-major, then G, then B order).
Output: data/<name>.lut  raw bytes, 33^3 x 3 (colour) or 33^3 x 1 (mono)
        src/lut_data.h   the same tables as C arrays

usage: genlut.py [json-dir]      (default: ./data/json)
"""
import json
import os
import sys

N = 33
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TABLES = [  # (C name, json base name, channels)
    ("lut_normal", "dt_Normal", 3),
    ("lut_photo", "dt_Photo", 3),
    ("lut_presentation", "dt_Presentation", 3),
    ("lut_web", "dt_Web", 3),
    ("lut_pop", "dt_POP", 3),
    ("lut_mono", "mono", 1),
]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data", "json")
    nodes = [min(255, round(i * 255 / (N - 1))) for i in range(N)]
    out = ["/* Generated by tools/genlut.py - do not edit. */",
           "/* 33x33x33 RGB grids measured from the Fuji Xerox C525A driver. */",
           "", "#define LUT_N %d" % N,
           "static const unsigned char lut_nodes[LUT_N] = { %s };" % ", ".join(map(str, nodes)), ""]
    for cname, jname, ch in TABLES:
        path = os.path.join(src, jname + ".json")
        if not os.path.exists(path):
            path = os.path.join(src, "lut33_" + jname + ".json")
        rows = json.load(open(path))[: N ** 3]
        for i, (rgb, _) in enumerate(rows):
            want = [nodes[i // (N * N)], nodes[(i // N) % N], nodes[i % N]]
            if rgb != want:
                sys.exit("%s: grid entry %d is %s, expected %s" % (path, i, rgb, want))
        data = bytes(v for _, val in rows for v in val[:ch])
        assert len(data) == N ** 3 * ch
        with open(os.path.join(ROOT, "data", cname[4:] + ".lut"), "wb") as f:
            f.write(data)
        out.append("static const unsigned char %s[%d] = {" % (cname, len(data)))
        for k in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[k:k + 24]) + ",")
        out.append("};")
        out.append("")
    with open(os.path.join(ROOT, "src", "lut_data.h"), "w") as f:
        f.write("\n".join(out))
    print("wrote src/lut_data.h and data/*.lut")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""genppd.py - write ppd/Dell_Color_Laser_1320c.ppd

Option names and media lists follow Dell's own 1320c PPD; paper sizes are the
ones whose HBPL codes were verified against the Fuji Xerox C525A driver.
"""
import os

FILTER = "/Library/Printers/Dell1320c/rastertodell1320c"
MARGIN = 11.28  # points, same printable area as the Fuji/Dell drivers

SIZES = [  # name, label, width, height (points)
    ("A4", "A4 (210 x 297mm)", 595, 842),
    ("Letter", 'Letter (8.5 x 11")', 612, 792),
    ("Legal", 'Legal (8.5 x 14")', 612, 1008),
    ("Executive", 'Executive (7.25 x 10.5")', 522, 756),
    ("FanFoldGermanLegal", 'Folio (8.5 x 13")', 612, 936),
    ("A5", "A5 (148 x 210mm)", 421, 595),
    ("B5", "B5 JIS (182 x 257mm)", 516, 729),
    ("Postcard", "Japanese Postcard (100 x 148mm)", 283, 420),
    ("Env10", 'Com 10 Envelope (4.125 x 9.5")', 297, 684),
    ("EnvMonarch", "Monarch Envelope (Portrait)", 279, 540),
    ("EnvMonarchRotated", "Monarch Envelope (Landscape)", 540, 279),
    ("EnvDL", "DL Envelope (Portrait)", 312, 624),
    ("EnvDLRotated", "DL Envelope (Landscape)", 624, 312),
    ("EnvC5", "C5 Envelope (162 x 229mm)", 459, 649),
    ("EnvC6Rotated", "C6 Envelope (Landscape)", 459, 323),
    ("EnvYou3Rotated", "Youkei 3 Envelope (Landscape)", 420, 278),
    ("EnvChou3", "Choukei 3 Envelope (120 x 235mm)", 340, 666),
]

MEDIA_TRAY1 = [
    ("Default", "Use Printer Settings"), ("Stationary", "Plain"), ("FinePaper", "Bond"), ("Envelope", "Envelope"),
    ("Postcard", "Postcard"), ("ThickPaper", "Heavyweight 1 (106-163g/m2)"),
    ("ThickPaper2", "Heavyweight 2 (164-216g/m2)"),
    ("CoatingPaper1", "Coated 1 (60-105g/m2)"), ("CoatingPaper2", "Coated 2 (106-163g/m2)"),
    ("CoatingPaper3", "Coated 3 (164-216g/m2)"), ("LabelPaper", "Labels"), ("Recycled", "Recycled"),
]
MEDIA_BYPASS = [
    ("Stationary", "Plain"), ("StationaryBack", "Plain - Side 2"),
    ("FinePaper", "Bond"), ("FinePaperBack", "Bond - Side 2"), ("Envelope", "Envelope"),
    ("Postcard", "Postcard"), ("PostcardBack", "Postcard - Side 2"),
    ("ThickPaper", "Heavyweight 1 (106-163g/m2)"), ("ThickPaperBack", "Heavyweight 1 - Side 2"),
    ("ThickPaper2", "Heavyweight 2 (164-216g/m2)"), ("ThickPaper2Back", "Heavyweight 2 - Side 2"),
    ("CoatingPaper1", "Coated 1 (60-105g/m2)"), ("CoatingPaper1Back", "Coated 1 - Side 2"),
    ("CoatingPaper2", "Coated 2 (106-163g/m2)"), ("CoatingPaper2Back", "Coated 2 - Side 2"),
    ("CoatingPaper3", "Coated 3 (164-216g/m2)"), ("LabelPaper", "Labels"),
    ("Recycled", "Recycled"), ("RecycledBack", "Recycled - Side 2"),
]


def pick_one(out, key, label, default, choices, order=None, code=lambda c: ""):
    out.append("*OpenUI *%s/%s: PickOne" % (key, label))
    if order is not None:
        out.append("*OrderDependency: %s AnySetup *%s" % (order, key))
    out.append("*Default%s: %s" % (key, default))
    for name, text in choices:
        out.append('*%s %s/%s: "%s"' % (key, name, text, code(name)))
    out.append("*CloseUI: *%s" % key)
    out.append("")


def main():
    o = []
    o += [
        '*PPD-Adobe: "4.3"',
        '*% Dell Color Laser 1320c - native driver for macOS (HBPL v1)',
        '*% Generated by tools/genppd.py',
        '*FormatVersion: "4.3"',
        '*FileVersion: "2.0"',
        '*LanguageVersion: English',
        '*LanguageEncoding: ISOLatin1',
        '*PCFileName: "DL1320CN.PPD"',
        '*Manufacturer: "Dell"',
        '*Product: "(Dell Color Laser 1320c)"',
        '*ModelName: "Dell Color Laser 1320c"',
        '*ShortNickName: "Dell Color Laser 1320c"',
        '*NickName: "Dell Color Laser 1320c (native)"',
        '*1284DeviceID: "MFG:Dell;CMD:PJL,RASTER,DOWNLOAD,HBPL,NEXTC;MDL:Color Laser 1320c;DES:Dell Color Laser 1320c;CLS:PRINTER;"',
        '*PSVersion: "(3010.000) 0"',
        '*LanguageLevel: "3"',
        '*ColorDevice: True',
        '*DefaultColorSpace: RGB',
        '*FileSystem: False',
        '*Throughput: "12"',
        '*LandscapeOrientation: Plus90',
        '*TTRasterizer: Type42',
        '*cupsVersion: 1.4',
        '*cupsModelNumber: 0',
        '*cupsManualCopies: False',
        '*cupsSNMPSupplies: False',
        '*APSupportsCustomColorMatching: True',
        '*cupsLanguages: "en"',
        '*cupsFilter: "application/vnd.cups-raster 0 %s"' % FILTER,
        '',
        '*OpenGroup: General/General',
        '',
    ]
    sizes = [(n, l) for n, l, _, _ in SIZES]
    o.append("*OpenUI *PageSize/Paper Size: PickOne")
    o.append("*OrderDependency: 10 AnySetup *PageSize")
    o.append("*DefaultPageSize: A4")
    for n, l, w, h in SIZES:
        o.append('*PageSize %s/%s: "<</PageSize[%d %d]/ImagingBBox null>>setpagedevice"' % (n, l, w, h))
    o.append("*CloseUI: *PageSize")
    o.append("")
    o.append("*OpenUI *PageRegion: PickOne")
    o.append("*OrderDependency: 10 AnySetup *PageRegion")
    o.append("*DefaultPageRegion: A4")
    for n, l, w, h in SIZES:
        o.append('*PageRegion %s/%s: "<</PageSize[%d %d]/ImagingBBox null>>setpagedevice"' % (n, l, w, h))
    o.append("*CloseUI: *PageRegion")
    o.append("")
    o.append("*DefaultImageableArea: A4")
    for n, l, w, h in SIZES:
        o.append('*ImageableArea %s/%s: "%.2f %.2f %.2f %.2f"' % (n, l, MARGIN, MARGIN, w - MARGIN, h - MARGIN))
    o.append("*DefaultPaperDimension: A4")
    for n, l, w, h in SIZES:
        o.append('*PaperDimension %s/%s: "%d %d"' % (n, l, w, h))
    o.append("")

    pick_one(o, "DLInputSlot", "Paper Source", "AutoSelect",
             [("AutoSelect", "Auto"), ("1stTray", "Tray 1"), ("BypassTray", "Manual Feeder")], 20)
    pick_one(o, "DLExtMediaTypeTray1", "Tray 1 Paper Type", "Default", MEDIA_TRAY1, 20)
    pick_one(o, "MediaType", "Manual Feeder Paper Type", "Stationary", MEDIA_BYPASS, 20)
    pick_one(o, "Collate", "Collate", "False", [("False", "Off"), ("True", "On")], 20)
    o.append("*CloseGroup: General")
    o.append("")
    o.append("*OpenGroup: Quality/Quality")
    o.append("")
    pick_one(o, "ColorModel", "Output Color", "RGB", [("RGB", "Color"), ("Gray", "Black")], 10,
             lambda c: "<</cupsColorSpace 1/cupsColorOrder 0/cupsBitsPerColor 8>>setpagedevice")
    pick_one(o, "DLOutputMode", "Print Mode", "600x600",
             [("600x600", "High Quality"), ("300x300", "High Speed")], 10,
             lambda c: "<</HWResolution[%s]>>setpagedevice" % c.replace("x", " "))
    o.insert(o.index("*OpenUI *DLOutputMode/Print Mode: PickOne"), "*DefaultResolution: 600dpi")
    pick_one(o, "DLDocumentType", "Image Types", "Normal",
             [("Normal", "Normal"), ("Photo", "Photo"), ("Presentation", "Presentation"),
              ("Web", "Web Pages"), ("POP", "POP"), ("Off", "Off")], 20)
    pick_one(o, "DLTonerSaver", "Draft Mode", "False", [("False", "Off"), ("True", "On")], 20)
    pick_one(o, "DLSkip", "Skip Blank Pages", "False", [("False", "Off"), ("True", "On")], 20)
    pick_one(o, "DLTurnPage", "Image Rotation (180deg)", "False", [("False", "Off"), ("True", "On")], 20)
    o.append("*CloseGroup: Quality")
    o.append("")
    o += [
        '*DefaultFont: Courier',
        '*Font Courier: Standard "(1.05)" Standard ROM',
        '*Font Helvetica: Standard "(1.05)" Standard ROM',
        '*Font Times-Roman: Standard "(1.05)" Standard ROM',
        '*% End of PPD',
        '',
    ]
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "ppd", "Dell_Color_Laser_1320c.ppd")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(o))
    print("wrote", path)


if __name__ == "__main__":
    main()
